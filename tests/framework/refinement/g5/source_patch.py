"""Deterministic source-only projection;raw patch always retained separately.
Exclude generated bytecode/native build products,not legitimate binary assets.
GIT binary patch is a representation (including our source text),not an artifact.
"""
import pathlib,re,shlex,subprocess
SUFFIXES={'.pyc','.pyo','.o','.obj','.so','.dylib','.dll','.a','.lib','.class','.exe','.whl','.egg'}
def artifact(path):
 p=pathlib.PurePosixPath(path);return '__pycache__' in p.parts or p.suffix.lower() in SUFFIXES or any(x in ('.pytest_cache','.mypy_cache','.ruff_cache') for x in p.parts)
def blocks(raw):
 if not raw:return []
 starts=[m.start() for m in re.finditer(br'(?m)^diff --git ',raw)]
 if not starts or starts[0]!=0:raise ValueError('Unexpected patch preamble')
 return [raw[a:b] for a,b in zip(starts,starts[1:]+[len(raw)])]
def block_paths(block):
 out=subprocess.run(['git','apply','--numstat','-z','--'],input=block+b'\n\n',capture_output=True,timeout=30)
 if out.returncode==0 and out.stdout:
  fields=out.stdout.split(b'\t',2)[2].split(b'\0');return [v.decode('utf-8','surrogateescape') for v in fields if v]
 header=block.splitlines()[0].decode('utf-8','surrogateescape');parts=shlex.split(header)
 if len(parts)!=4 or parts[:2]!=['diff','--git']:raise ValueError('Unrecognized patch header;do not silently discard')
 return [v[2:] if v.startswith(('a/','b/')) else v for v in parts[2:]]
def project(raw):
 kept=[];excluded=[];pyc=[];binary_files=0
 for block in blocks(raw):
  paths=block_paths(block);binary_files+=int(b'\nBinary files ' in block)
  if any(pathlib.PurePosixPath(p).suffix.lower()=='.pyc' for p in paths):pyc.extend(paths)
  if any(artifact(p) for p in paths):excluded.extend(paths)
  else:kept.append(block)
 # Preserve every byte of retained blocks,including binary-patch terminators.
 clean=b''.join(kept)
 return clean,dict(excluded_paths=sorted(set(excluded)),pyc_paths=sorted(set(pyc)),binary_files_entries=binary_files,raw_blocks=len(blocks(raw)),source_blocks=len(kept))
